"""PipeWire filter-chain configuration generator and installer."""

from __future__ import annotations

from pathlib import Path
import shutil
import subprocess


DEFAULT_CONF_DIR = Path.home() / ".config" / "pipewire" / "pipewire.conf.d"
CONF_PREFIX = "opendolby-"
LSP_LIMITER_URI = "http://lsp-plug.in/plugins/lv2/limiter_stereo"


def has_lv2_plugin(uri: str) -> bool:
    """Return True if lv2ls reports the given LV2 plugin URI."""
    if shutil.which("lv2ls") is None:
        return False
    res = subprocess.run(["lv2ls"], capture_output=True, text=True, check=False)
    return res.returncode == 0 and uri in res.stdout.splitlines()


def detect_speaker_sink() -> str | None:
    """Detect the active ALSA speaker sink node.name via pw-cli if available."""
    if shutil.which("pw-cli") is None:
        return None
    res = subprocess.run(["pw-cli", "ls", "Node"], capture_output=True, text=True, check=False)
    if res.returncode != 0:
        return None
    for line in res.stdout.splitlines():
        if "node.name" in line and "Speaker__sink" in line:
            parts = line.split('"')
            if len(parts) >= 2:
                return parts[1]
    return None


def render_filter_chain_conf(
    profile_name: str,
    irs_path: Path,
    sample_rate: int = 48000,
    target_sink: str | None = None,
    use_limiter: bool | None = None,
) -> str:
    """Render a PipeWire libpipewire-module-filter-chain config string."""
    if use_limiter is None:
        use_limiter = has_lv2_plugin(LSP_LIMITER_URI)

    irs_abs = str(irs_path.resolve())
    desc = f"OpenDolby ({profile_name})"

    nodes = [
        f"""                {{
                    type = builtin
                    name = conv_l
                    label = convolver
                    config = {{
                        filename = "{irs_abs}"
                        channel = 0
                        gain = 1.0
                    }}
                }}""",
        f"""                {{
                    type = builtin
                    name = conv_r
                    label = convolver
                    config = {{
                        filename = "{irs_abs}"
                        channel = 1
                        gain = 1.0
                    }}
                }}""",
    ]

    links = []
    if use_limiter:
        nodes.append(
            f"""                {{
                    type = lv2
                    name = lim
                    plugin = "{LSP_LIMITER_URI}"
                    control = {{
                        th = -0.5
                        lk = 2.0
                        at = 1.0
                        rt = 50.0
                    }}
                }}"""
        )
        links = [
            '                { output = "conv_l:Out" input = "lim:in_l" }',
            '                { output = "conv_r:Out" input = "lim:in_r" }',
        ]
        outputs = '            outputs = [ "lim:out_l" "lim:out_r" ]'
    else:
        outputs = '            outputs = [ "conv_l:Out" "conv_r:Out" ]'

    playback_props = ['                node.name = "opendolby.playback"']
    if target_sink:
        playback_props.append(f'                target.object = "{target_sink}"')
    playback_props.append("                node.passive = true")

    nodes_block = "\n".join(nodes)
    links_block = f"\n            links = [\n" + "\n".join(links) + "\n            ]" if links else ""
    playback_block = "\n".join(playback_props)

    return f"""# Generated by OpenDolby for profile: {profile_name}
context.modules = [
    {{
        name = libpipewire-module-filter-chain
        flags = [ ifexists nofail ]
        args = {{
            node.description = "{desc}"
            media.name = "{desc}"
            filter.graph = {{
                nodes = [
{nodes_block}
                ]{links_block}
            }}
            inputs = [ "conv_l:In" "conv_r:In" ]
{outputs}
            capture.props = {{
                node.name = "opendolby.{profile_name}"
                media.class = Audio/Sink
                audio.channels = 2
                audio.position = [ FL FR ]
                audio.rate = {sample_rate}
            }}
            playback.props = {{
{playback_block}
            }}
        }}
    }}
]
"""


def uninstall_profiles(conf_dir: Path = DEFAULT_CONF_DIR) -> list[Path]:
    """Remove all OpenDolby-generated configs and .irs files from PipeWire conf.d."""
    removed: list[Path] = []
    if not conf_dir.exists():
        return removed
    for path in sorted(conf_dir.iterdir()):
        if path.name.startswith(CONF_PREFIX) and path.suffix in (".conf", ".irs"):
            path.unlink()
            removed.append(path)
    return removed


def restart_pipewire() -> None:
    """Restart user PipeWire and WirePlumber services."""
    subprocess.run(
        ["systemctl", "--user", "restart", "pipewire.service", "pipewire-pulse.service", "wireplumber.service"],
        check=True,
    )
